func TestDNSForwarderRelaysUDPAndFallsBackToNextUpstream(t *testing.T) {
	defer func(old time.Duration) { dnsUpstreamTimeout = old }(dnsUpstreamTimeout)
	dnsUpstreamTimeout = 300 * time.Millisecond
	defer func(old time.Duration) { dnsProbeTimeout = old }(dnsProbeTimeout)
	dnsProbeTimeout = 2 * time.Second

	// The first upstream swallows queries (like a blocked resolver); the forwarder
	// must move on to the second, which answers.
	upstreams := []string{fakeResolver(t, false), fakeResolver(t, true)}
	f, err := listenDNSForwarder("127.0.0.1:0", upstreams, slog.New(slog.NewTextHandler(io.Discard, nil)))
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()

	if err := probeDNS(f.udp.LocalAddr().String()); err != nil {
		t.Fatalf("query through the forwarder failed: %v", err)
	}
}

func TestDNSForwarderRelaysTCP(t *testing.T) {
	// DNS over TCP passes through byte for byte, so an echoing upstream is enough.
	upstream, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	defer upstream.Close()
	go func() {
		for {
			conn, err := upstream.Accept()
			if err != nil {
				return
			}
			go func() {
				defer conn.Close()
				_, _ = io.Copy(conn, conn)
			}()
		}
	}()

	f, err := listenDNSForwarder("127.0.0.1:0", []string{upstream.Addr().String()}, slog.New(slog.NewTextHandler(io.Discard, nil)))
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()

	conn, err := net.DialTimeout("tcp", f.tcp.Addr().String(), time.Second)
	if err != nil {
		t.Fatal(err)
	}
	defer conn.Close()
	_ = conn.SetDeadline(time.Now().Add(2 * time.Second))
	msg := []byte{0, 3, 'a', 'b', 'c'}
	if _, err := conn.Write(msg); err != nil {
		t.Fatal(err)
	}
	got := make([]byte, len(msg))
	if _, err := io.ReadFull(conn, got); err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(got, msg) {
		t.Fatalf("relayed %v, want %v", got, msg)
	}
}

func TestResolvConfNameservers(t *testing.T) {
	path := filepath.Join(t.TempDir(), "resolv.conf")
	content := `# Generated by Docker
nameserver 127.0.0.11
search example.internal
options ndots:0
nameserver fe80::1%eth0
nameserver not-an-ip
nameserver 9.9.9.9
`
	if err := os.WriteFile(path, []byte(content), 0600); err != nil {
		t.Fatal(err)
	}
	got, err := resolvConfNameservers(path)
	if err != nil {
		t.Fatal(err)
	}
	want := []string{"127.0.0.11:53", "[fe80::1%eth0]:53", "9.9.9.9:53"}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("resolvConfNameservers = %v, want %v", got, want)
	}
}
